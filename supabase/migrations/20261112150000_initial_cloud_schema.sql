create or replace function public.student_results()
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare uid bigint := public.assert_role(array['student']);
begin
  return jsonb_build_object(
    'attempts',coalesce((select jsonb_agg(jsonb_build_object('id',x.id,'mode',x.mode,'source_type',x.source_type,'submitted_at',x.submitted_at,'score',x.score,'duration_sec',x.duration_sec,'questionIds',x.question_ids) order by x.submitted_at desc) from (
      select a.id,e.mode,e.source_type,a.submitted_at,a.score,a.duration_sec,e.settings_json->'questionIds' question_ids
