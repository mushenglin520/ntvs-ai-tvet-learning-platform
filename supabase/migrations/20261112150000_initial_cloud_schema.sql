      select u.unit_name,count(*) total,count(*) filter(where not r.is_correct) wrong from public.responses r join public.attempts a on a.id=r.attempt_id join public.questions q on q.id=r.question_id join public.units u on u.id=q.unit_id where a.student_id=uid group by u.id,u.unit_name
    ) w),'[]'::jsonb)
  );
end;
$$;

