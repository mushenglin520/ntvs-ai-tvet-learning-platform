create or replace function public.request_session_token()
returns uuid language plpgsql stable security invoker set search_path = public as $$
declare raw_token text;
begin
  raw_token := coalesce(current_setting('request.headers', true)::jsonb ->> 'x-session-token', '');
  if raw_token = '' then return null; end if;
  begin return raw_token::uuid; exception when invalid_text_representation then return null; end;
end;
$$;

create or replace function public.session_user_id()
returns bigint language sql stable security definer set search_path = public as $$
  select s.user_id from public.sessions s
  where s.token = public.request_session_token() and s.expires_at > now()
  limit 1
$$;

create or replace function public.session_role()
returns text language sql stable security definer set search_path = public as $$
  select p.role from public.profiles p where p.id = public.session_user_id()
$$;

create or replace function public.assert_role(allowed_roles text[])
returns bigint language plpgsql stable security definer set search_path = public as $$
declare uid bigint := public.session_user_id(); current_role text := public.session_role();
begin
  if uid is null then raise exception '尚未登入' using errcode = '28000'; end if;
  if not (current_role = any(allowed_roles)) then raise exception '權限不足' using errcode = '42501'; end if;
  return uid;
end;
$$;

create or replace function public.login_user(p_login_id text, p_password text)
returns jsonb language plpgsql security definer set search_path = public, extensions as $$
declare p public.profiles; new_token uuid := extensions.gen_random_uuid(); expires_at timestamptz := now() + interval '8 hours';
begin
  select * into p from public.profiles where login_id = trim(p_login_id) limit 1;
  if p.id is null or p.password_hash <> extensions.crypt(p_password, p.password_hash) then
    raise exception '帳號或密碼不正確' using errcode = '28000';
  end if;
  delete from public.sessions where expires_at <= now();
  insert into public.sessions(token, user_id, expires_at) values (new_token, p.id, expires_at);
  return jsonb_build_object('token', new_token, 'expiresAt', expires_at, 'role', p.role);
end;
$$;

create or replace function public.logout_user()
returns void language sql security definer set search_path = public as $$
  delete from public.sessions where token = public.request_session_token()
$$;

create or replace function public.get_current_user()
returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object('id', p.id, 'loginId', p.login_id, 'displayName', p.display_name,
    'role', p.role, 'classCode', p.class_code)
  from public.profiles p where p.id = public.session_user_id()
$$;

create or replace function public.list_units()
returns jsonb language plpgsql stable security definer set search_path = public as $$
begin
  perform public.assert_role(array['student','teacher','admin']);
  return coalesce((select jsonb_agg(jsonb_build_object('id', id, 'name', unit_name) order by id) from public.units), '[]'::jsonb);
end;
$$;

create or replace function public.build_public_questions(p_source_type text, p_unit_id bigint, p_difficulty text, p_count integer)
returns jsonb language sql volatile security definer set search_path = public as $$
  select coalesce(jsonb_agg(jsonb_build_object(
    'id', x.id, 'stem', x.stem, 'options', x.options_json, 'unitName', x.unit_name,
    'difficulty', x.difficulty, 'sourceType', x.source_type, 'sourceLabel', x.source_label
  )), '[]'::jsonb)
  from (
    select q.id, q.stem, q.options_json, u.unit_name, q.difficulty, q.source_type, q.source_label
    from public.questions q join public.units u on u.id = q.unit_id
    where q.status = 'approved' and q.source_type = p_source_type
      and (p_unit_id is null or q.unit_id = p_unit_id)
      and (p_difficulty is null or q.difficulty = p_difficulty)
    order by random() limit greatest(1, least(p_count, 50))
  ) x
$$;

create or replace function public.start_exam(p_mode text, p_source_type text, p_unit_id bigint default null, p_difficulty text default null, p_count integer default 5)
returns jsonb language plpgsql security definer set search_path = public as $$
declare uid bigint := public.assert_role(array['student']); question_list jsonb; exam_id bigint; attempt_id bigint;
begin
  if p_mode not in ('practice','mock') or p_source_type not in ('official','ai') then raise exception '考試設定不正確'; end if;
  question_list := public.build_public_questions(p_source_type, p_unit_id, case when p_mode='mock' then null else p_difficulty end, p_count);
  if jsonb_array_length(question_list) = 0 then raise exception '目前沒有符合條件的已審題目'; end if;
  insert into public.exams(mode, source_type, subject_id, settings_json, created_by)
  values (p_mode, p_source_type, 1, jsonb_build_object('sourceType',p_source_type,'unitId',p_unit_id,'difficulty',p_difficulty,
    'count',p_count,'questionIds',(select jsonb_agg((v->>'id')::bigint) from jsonb_array_elements(question_list) v)), uid)
  returning id into exam_id;
  insert into public.attempts(exam_id, student_id) values (exam_id, uid) returning id into attempt_id;
  return jsonb_build_object('attemptId', attempt_id, 'questions', question_list);
end;
$$;

create or replace function public.answer_practice(p_attempt_id bigint, p_question_id bigint, p_selected_answer text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare uid bigint := public.assert_role(array['student']); a record; q record; correct boolean;
begin
  select at.submitted_at, e.mode, e.settings_json into a from public.attempts at join public.exams e on e.id=at.exam_id
  where at.id=p_attempt_id and at.student_id=uid;
  if not found or a.mode <> 'practice' then raise exception '找不到練習紀錄'; end if;
  if a.submitted_at is not null then raise exception '此練習已完成'; end if;
  if not (a.settings_json->'questionIds' @> to_jsonb(array[p_question_id])) then raise exception '題目不屬於本次練習'; end if;
  select qn.answer, qn.explanation, u.unit_name into q from public.questions qn join public.units u on u.id=qn.unit_id
  where qn.id=p_question_id and qn.status='approved';
  if not found then raise exception '題目尚未發布'; end if;
  correct := upper(p_selected_answer)=q.answer;
  insert into public.responses(attempt_id,question_id,selected_answer,is_correct) values (p_attempt_id,p_question_id,upper(p_selected_answer),correct)
  on conflict (attempt_id,question_id) do update set selected_answer=excluded.selected_answer,is_correct=excluded.is_correct,answered_at=now();
  return jsonb_build_object('correct',correct,'correctAnswer',q.answer,'explanation',q.explanation,'unitName',q.unit_name);
end;
$$;

create or replace function public.finish_practice(p_attempt_id bigint)
returns jsonb language plpgsql security definer set search_path = public as $$
declare uid bigint := public.assert_role(array['student']); a record; total integer; correct integer; final_score numeric;
begin
  select at.*, e.mode, e.settings_json into a from public.attempts at join public.exams e on e.id=at.exam_id
  where at.id=p_attempt_id and at.student_id=uid;
  if not found or a.mode <> 'practice' then raise exception '找不到練習'; end if;
  if a.submitted_at is not null then raise exception '此練習已完成'; end if;
  total := jsonb_array_length(a.settings_json->'questionIds');
  select count(*)::integer into correct from public.responses where attempt_id=p_attempt_id and is_correct;
  final_score := case when total=0 then 0 else round(correct::numeric*100/total) end;
  update public.attempts set submitted_at=now(), score=final_score, duration_sec=extract(epoch from (now()-started_at))::integer where id=p_attempt_id;
  return jsonb_build_object('score',final_score,'correct',correct,'total',total);
end;
$$;

create or replace function public.submit_mock(p_attempt_id bigint, p_answers jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare uid bigint := public.assert_role(array['student']); a record; qid bigint; q record; selected text; ok boolean; correct integer:=0; total integer; details jsonb:='[]'::jsonb; final_score numeric;
begin
  select at.*, e.mode, e.settings_json into a from public.attempts at join public.exams e on e.id=at.exam_id
  where at.id=p_attempt_id and at.student_id=uid;
  if not found or a.mode <> 'mock' then raise exception '找不到考試紀錄'; end if;
  if a.submitted_at is not null then raise exception '此考試已交卷，不能重複提交'; end if;
  total := jsonb_array_length(a.settings_json->'questionIds');
  for qid in select value::bigint from jsonb_array_elements_text(a.settings_json->'questionIds') loop
    select answer, explanation into q from public.questions where id=qid and status='approved';
    selected := nullif(upper(p_answers->>qid::text),''); ok := selected is not null and selected=q.answer;
    if ok then correct:=correct+1; end if;
    if selected is not null then
      insert into public.responses(attempt_id,question_id,selected_answer,is_correct) values (p_attempt_id,qid,selected,ok)
      on conflict (attempt_id,question_id) do update set selected_answer=excluded.selected_answer,is_correct=excluded.is_correct,answered_at=now();
    end if;
    details := details || jsonb_build_array(jsonb_build_object('questionId',qid,'selectedAnswer',selected,'correctAnswer',q.answer,'isCorrect',ok,'explanation',q.explanation));
  end loop;
  final_score := case when total=0 then 0 else round(correct::numeric*100/total) end;
  update public.attempts set submitted_at=now(),score=final_score,duration_sec=extract(epoch from (now()-started_at))::integer where id=p_attempt_id;
  return jsonb_build_object('score',final_score,'correct',correct,'total',total,'details',details);
end;
$$;

