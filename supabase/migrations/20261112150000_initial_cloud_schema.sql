create extension if not exists pgcrypto with schema extensions;

create table public.departments (
  id bigint generated by default as identity primary key,
  school text not null,
  group_name text not null,
  department_name text not null,
  code text not null unique
);

create table public.profiles (
  id bigint generated by default as identity primary key,
  login_id text not null unique,
  password_hash text not null,
  display_name text not null,
  role text not null check (role in ('admin', 'teacher', 'student')),
  department_id bigint not null references public.departments(id),
  class_code text
);

create table public.subjects (
  id bigint generated by default as identity primary key,
  department_id bigint not null references public.departments(id),
  subject_name text not null,
  curriculum_version text not null
);

create table public.units (
  id bigint generated by default as identity primary key,
  subject_id bigint not null references public.subjects(id),
  unit_name text not null,
  parent_id bigint references public.units(id)
);

create table public.source_documents (
  id bigint generated by default as identity primary key,
  year integer not null,
  subject_id bigint not null references public.subjects(id),
  url text not null,
  filename text not null,
  sha256 text,
  page_count integer,
  import_status text not null,
  downloaded_at timestamptz,
  note text
);

create table public.questions (
  id bigint generated by default as identity primary key,
  source_type text not null check (source_type in ('official', 'ai')),
  source_document_id bigint references public.source_documents(id),
  original_no text,
  stem text not null,
  options_json jsonb not null,
  answer text not null check (answer in ('A', 'B', 'C', 'D')),
  explanation text not null,
  unit_id bigint not null references public.units(id),
  difficulty text not null check (difficulty in ('基礎', '進階', '挑戰')),
  status text not null check (status in ('pending', 'approved', 'returned', 'rejected')),
  version integer not null default 1,
  is_demo boolean not null default true,
  source_label text not null,
  created_at timestamptz not null default now()
);

create table public.question_reviews (
  id bigint generated by default as identity primary key,
  question_id bigint not null references public.questions(id),
  reviewer_id bigint not null references public.profiles(id),
  decision text not null check (decision in ('approved', 'returned', 'rejected')),
  note text not null,
  reviewed_at timestamptz not null default now(),
  version integer not null
);

create table public.exams (
  id bigint generated by default as identity primary key,
  mode text not null check (mode in ('practice', 'mock')),
  source_type text not null check (source_type in ('official', 'ai', 'mixed')),
  subject_id bigint not null references public.subjects(id),
  settings_json jsonb not null,
  created_by bigint not null references public.profiles(id),
  published_at timestamptz not null default now()
);

create table public.attempts (
  id bigint generated by default as identity primary key,
  exam_id bigint not null references public.exams(id),
  student_id bigint not null references public.profiles(id),
  started_at timestamptz not null default now(),
  submitted_at timestamptz,
  score numeric(5,2),
  duration_sec integer
);

create table public.responses (
  id bigint generated by default as identity primary key,
  attempt_id bigint not null references public.attempts(id),
  question_id bigint not null references public.questions(id),
  selected_answer text not null check (selected_answer in ('A', 'B', 'C', 'D')),
  is_correct boolean not null,
  answered_at timestamptz not null default now(),
  unique (attempt_id, question_id)
);

create table public.audit_logs (
  id bigint generated by default as identity primary key,
  actor_id bigint not null references public.profiles(id),
  action text not null,
  target_type text not null,
  target_id text not null,
  created_at timestamptz not null default now(),
  metadata_json jsonb not null default '{}'::jsonb
);

create table public.sessions (
  token uuid primary key default extensions.gen_random_uuid(),
  user_id bigint not null references public.profiles(id) on delete cascade,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

create index idx_questions_student_bank on public.questions(status, source_type, unit_id);
