create or replace function public.review_question(p_question_id bigint, p_decision text, p_note text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare uid bigint := public.assert_role(array['teacher']); q public.questions;
begin
  if p_decision not in ('approved','returned','rejected') or length(trim(p_note))<2 then raise exception '審核資料不完整'; end if;
  select * into q from public.questions where id=p_question_id for update;
  if q.id is null then raise exception '找不到題目'; end if;
  if q.status<>'pending' then raise exception '此題已完成審核，請重新整理'; end if;
  update public.questions set status=p_decision where id=q.id;
  insert into public.question_reviews(question_id,reviewer_id,decision,note,version) values(q.id,uid,p_decision,trim(p_note),q.version);
  insert into public.audit_logs(actor_id,action,target_type,target_id,metadata_json) values(uid,'question.review','question',q.id::text,jsonb_build_object('decision',p_decision,'note',trim(p_note),'version',q.version));
  return jsonb_build_object('ok',true,'status',p_decision);
end;
$$;

create or replace function public.import_source_document(p_year integer, p_url text, p_filename text, p_sha256 text, p_status text, p_note text, p_questions jsonb default '[]'::jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare uid bigint := public.assert_role(array['teacher']); doc_id bigint; item jsonb; unit_id bigint; imported integer:=0;
begin
  insert into public.source_documents(year,subject_id,url,filename,sha256,import_status,downloaded_at,note) values(p_year,1,p_url,p_filename,p_sha256,p_status,now(),p_note) returning id into doc_id;
  for item in select value from jsonb_array_elements(coalesce(p_questions,'[]'::jsonb)) loop
    select id into unit_id from public.units where unit_name=item->>'unit' limit 1;
    if unit_id is null then raise exception '單元不存在：%',item->>'unit'; end if;
    if upper(item->>'answer') not in ('A','B','C','D') then raise exception '答案須為 A-D'; end if;
    insert into public.questions(source_type,source_document_id,original_no,stem,options_json,answer,explanation,unit_id,difficulty,status,source_label)
    values(case when item->>'source_type'='official' then 'official' else 'ai' end,doc_id,item->>'original_no',item->>'stem',item->'options',upper(item->>'answer'),item->>'explanation',unit_id,
      case when item->>'difficulty' in ('基礎','進階','挑戰') then item->>'difficulty' else '基礎' end,'pending','匯入待審示範資料');
    imported:=imported+1;
  end loop;
  insert into public.audit_logs(actor_id,action,target_type,target_id,metadata_json) values(uid,'source.import','source_document',doc_id::text,jsonb_build_object('filename',p_filename,'sha256',p_sha256,'imported',imported));
  return jsonb_build_object('documentId',doc_id,'imported',imported);
end;
$$;

